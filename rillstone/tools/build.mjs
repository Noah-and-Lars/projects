// Builds the single-file game: rillstone/index.html.
//
// Bundles src/js (with three.js, Rapier and fflate from node_modules, at the
// same versions the dev import map loads) into one minified script, and
// inlines it together with style.css and the icon into src/index.html. Web
// Workers are bundled first, each into a string the main script starts from a
// Blob URL (see src/js/core/workers.js). The result makes no outside requests
// except the optional realtime server, so it can be dropped onto any static
// host or opened offline.
//
//   cd rillstone/tools && npm install && npm run build
import { build } from 'esbuild';
import { readFileSync, writeFileSync, statSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const src = join(root, 'src');
const read = (p) => readFileSync(join(src, p), 'utf8');

const pkg = (name) => JSON.parse(readFileSync(join(here, 'node_modules', name, 'package.json'), 'utf8')).version;
const LIBS = ['three', '@dimforge/rapier3d-compat', 'fflate'];
const versions = Object.fromEntries(LIBS.map(n => [n, pkg(n)]));

// The dev import map must point at the same versions we bundle, and match package.json.
const html = read('index.html');
const want = JSON.parse(readFileSync(join(here, 'package.json'), 'utf8')).devDependencies;
for (const [name, v] of Object.entries(versions)) {
  if (want[name] !== v) throw new Error(`tools/package.json wants ${name}@${want[name]} but node_modules has ${v}: run npm install`);
  if (!html.includes(`${name}@${v}/`)) throw new Error(`src/index.html import map does not load ${name}@${v}`);
}

const common = {
  bundle: true, format: 'iife', minify: true, target: ['es2020', 'safari15'],
  legalComments: 'none', logOverride: { 'empty-import-meta': 'silent' }, nodePaths: [join(here, 'node_modules')], write: false, logLevel: 'warning',
};

// 1. Workers, each into a string.
const workers = {};
for (const f of readdirSync(join(src, 'js', 'workers')).filter(f => f.endsWith('.js'))) {
  const r = await build({ ...common, entryPoints: [join(src, 'js', 'workers', f)] });
  workers[f.replace(/\.js$/, '')] = r.outputFiles[0].text;
}

// 2. The game, with the workers defined in.
const result = await build({ ...common, entryPoints: [join(src, 'js', 'main.js')], define: { __RILL_WORKERS__: JSON.stringify(workers) } });
// Never let the inline script close its own <script> tag early.
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');

const css = read('style.css').replace(/<\/style/gi, '<\\/style');
const iconUri = 'data:image/svg+xml;base64,' + Buffer.from(read('icon.svg')).toString('base64');

const notice = `<!--
  Rillstone — a first-person mining and water-automation sandbox.
  Single-file build generated by tools/build.mjs from src/. Do not edit this
  file by hand: edit src/ and run the build again.

  Includes three.js ${versions.three} (https://threejs.org/), MIT License,
  Copyright © 2010-2025 three.js authors; Rapier ${versions['@dimforge/rapier3d-compat']}
  (https://rapier.rs/), Apache License 2.0, Copyright 2020 Sébastien Crozet;
  and fflate ${versions.fflate} (https://github.com/101arrowz/fflate), MIT License,
  Copyright (c) 2023 Arjun Barrett. Full licence texts are in
  tools/THIRD_PARTY_LICENSES.txt.
-->`;

let out = html;
const swap = (from, to) => {
  if (!out.includes(from)) throw new Error('build: could not find in src/index.html: ' + from.slice(0, 80));
  out = out.replace(from, () => to);
};
out = out.replace(/\s*<script type="importmap">[\s\S]*?<\/script>/, '');
swap('<link rel="icon" href="icon.svg" type="image/svg+xml">', `<link rel="icon" href="${iconUri}" type="image/svg+xml">`);
swap('<link rel="stylesheet" href="style.css">', `<style>\n${css}</style>`);
swap('<script type="module" src="js/main.js"></script>', `<script>${js}</script>`);
out = out.replace('<!doctype html>\n', `<!doctype html>\n${notice}\n`);

const dest = join(root, 'index.html');
writeFileSync(dest, out);
const kb = (statSync(dest).size / 1024).toFixed(0);
console.log(`wrote ${dest} (${kb} KB; ${LIBS.map(n => n + ' ' + versions[n]).join(', ')})`);
if (statSync(dest).size > 8 * 1024 * 1024) throw new Error('single file is over the 8 MB budget (BUILD_BRIEF section 8)');
