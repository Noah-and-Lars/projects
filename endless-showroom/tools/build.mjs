// Builds the single-file game: endless-showroom/index.html.
//
// Bundles src/js (with three.js from node_modules, at the same version the
// dev import map loads) into one minified script, and inlines it with
// style.css and the icon into src/index.html. The online mode loads the
// arcade's realtime client (rt.js) when you choose to play online; nothing
// else is fetched, so solo play works offline.
//
//   cd endless-showroom/tools && npm install && npm run build
import { build } from 'esbuild';
import { readFileSync, writeFileSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const src = join(root, 'src');
const read = (p) => readFileSync(join(src, p), 'utf8');
const three = JSON.parse(readFileSync(join(here, 'node_modules', 'three', 'package.json'), 'utf8')).version;

const html = read('index.html');
if (!html.includes(`three@${three}/`)) throw new Error(`src/index.html import map does not load three@${three}`);

const result = await build({
  entryPoints: [join(src, 'js', 'main.js')],
  bundle: true, format: 'iife', minify: process.env.DEV !== '1', target: ['es2020', 'safari15'], legalComments: 'none',
  nodePaths: [join(here, 'node_modules')], write: false, logLevel: 'warning',
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
// the UI typeface (Barlow Condensed, SIL OFL) is inlined so solo play stays offline
const css = read('style.css').replace(/url\('fonts\/([\w-]+\.woff2)'\)/g, (m, f) => `url('data:font/woff2;base64,${readFileSync(join(src, 'fonts', f)).toString('base64')}')`).replace(/<\/style/gi, '<\\/style');
const iconUri = 'data:image/svg+xml;base64,' + Buffer.from(read('icon.svg')).toString('base64');
const notice = `<!--
  Endless Showroom — survive an endless furniture store with friends.
  Single-file build generated by tools/build.mjs from src/. Do not edit this
  file by hand: edit src/ and run the build again.

  Includes the Barlow Condensed typeface (SIL Open Font License 1.1, Copyright 2017
  The Barlow Project Authors).
  Includes three.js ${three} (https://threejs.org/), MIT License,
  Copyright © 2010-2024 three.js authors. Licence text in tools/THIRD_PARTY_LICENSES.txt.
-->`;

let out = html;
const swap = (from, to) => {
  if (!out.includes(from)) throw new Error('build: could not find in src/index.html: ' + from.slice(0, 80));
  out = out.replace(from, () => to);
};
out = out.replace(/\s*<script type="importmap">[\s\S]*?<\/script>/, '');
swap('<link rel="icon" href="icon.svg" type="image/svg+xml">', `<link rel="icon" href="${iconUri}" type="image/svg+xml">`);
swap('<link rel="apple-touch-icon" id="apple-icon" href="icon.svg">', `<link rel="apple-touch-icon" id="apple-icon" href="${iconUri}">`);
swap('<link rel="stylesheet" href="style.css">', `<style>\n${css}</style>`);
swap('<script type="module" src="js/main.js"></script>', `<script>${js}</script>`);
out = out.replace('<!doctype html>\n', `<!doctype html>\n${notice}\n`);
const dest = join(root, process.env.DEV === '1' ? 'index-dev.html' : 'index.html'); // DEV=1: readable, for profiling (not shipped)
writeFileSync(dest, out);
console.log(`wrote ${dest} (${(statSync(dest).size / 1024).toFixed(0)} KB; three ${three})`);
