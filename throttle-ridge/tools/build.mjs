// Builds the single-file game: throttle-ridge/index.html.
//
// Bundles src/js (with three.js and planck.js from node_modules, at the same
// versions the dev import map loads) into one minified script, and inlines it
// together with style.css and the icon into src/index.html. The result has no
// external requests, so it can be dropped onto any static host or opened
// offline.
//
//   cd throttle-ridge/tools && npm install && npm run build
import { build } from 'esbuild';
import { readFileSync, writeFileSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const src = join(root, 'src');
const read = (p) => readFileSync(join(src, p), 'utf8');

const pkg = (name) => JSON.parse(readFileSync(join(here, 'node_modules', name, 'package.json'), 'utf8')).version;
const versions = { three: pkg('three'), planck: pkg('planck') };

// The dev import map must point at the same versions we bundle.
const html = read('index.html');
for (const [name, v] of Object.entries(versions)) {
  if (!html.includes(`${name}@${v}/`)) throw new Error(`src/index.html import map does not load ${name}@${v}`);
}

const result = await build({
  entryPoints: [join(src, 'js', 'main.js')],
  bundle: true,
  format: 'iife',
  minify: true,
  target: ['es2020', 'safari15'],
  legalComments: 'none',
  nodePaths: [join(here, 'node_modules')],
  write: false,
  logLevel: 'warning',
});
// Never let the inline script close its own <script> tag early.
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');

const css = read('style.css').replace(/<\/style/gi, '<\\/style');
const iconUri = 'data:image/svg+xml;base64,' + Buffer.from(read('icon.svg')).toString('base64');

const notice = `<!--
  Throttle Ridge — a side-scrolling motocross game.
  Single-file build generated by tools/build.mjs from src/. Do not edit this
  file by hand: edit src/ and run the build again.

  Includes three.js ${versions.three} (https://threejs.org/), MIT License,
  Copyright © 2010-2024 three.js authors; and planck.js ${versions.planck}
  (https://piqnt.com/planck.js/), MIT License, Copyright (c) Erin Catto,
  Ali Shakiba. Full licence texts are in tools/THIRD_PARTY_LICENSES.txt.
-->`;

let out = html;
const swap = (from, to) => {
  if (!out.includes(from)) throw new Error('build: could not find in src/index.html: ' + from.slice(0, 80));
  out = out.replace(from, () => to);
};
// Import map: not needed, everything is bundled.
out = out.replace(/\s*<script type="importmap">[\s\S]*?<\/script>/, '');
// Manifest: relative start_url/scope can't work from an inline file, so the
// single-file build leaves it out (the page still runs full screen when added
// to the home screen via the apple-mobile-web-app meta tags).
swap('<link rel="manifest" href="manifest.webmanifest">\n', '');
swap('<link rel="icon" href="icon.svg" type="image/svg+xml">', `<link rel="icon" href="${iconUri}" type="image/svg+xml">`);
swap('<link rel="apple-touch-icon" id="apple-icon" href="icon.svg">', `<link rel="apple-touch-icon" id="apple-icon" href="${iconUri}">`);
swap('<link rel="stylesheet" href="style.css">', `<style>\n${css}</style>`);
swap('<script type="module" src="js/main.js"></script>', `<script>${js}</script>`);
out = out.replace('<!doctype html>\n', `<!doctype html>\n${notice}\n`);

const dest = join(root, 'index.html');
writeFileSync(dest, out);
console.log(`wrote ${dest} (${(statSync(dest).size / 1024).toFixed(0)} KB; three ${versions.three}, planck ${versions.planck})`);
