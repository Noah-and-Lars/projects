// Builds the single-file game: loamline/index.html.
//
// Bundles src/js (with three.js from node_modules, at the version the dev
// import map loads) into one minified script, and inlines it together with
// style.css, the fonts and the icon into src/index.html. The result makes no
// outside requests, so it runs from any static host or straight off disk.
//
//   cd loamline/tools && npm install && npm run build
import { build } from 'esbuild';
import { readFileSync, writeFileSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const src = join(root, 'src');
const read = (p) => readFileSync(join(src, p), 'utf8');
const b64 = (p) => readFileSync(join(src, p)).toString('base64');

const threeV = JSON.parse(readFileSync(join(here, 'node_modules', 'three', 'package.json'), 'utf8')).version;
const html = read('index.html');
if (!html.includes(`three@${threeV}/`)) throw new Error(`src/index.html import map does not load three@${threeV}`);

const result = await build({
  entryPoints: [join(src, 'js', 'main.js')],
  bundle: true,
  format: 'iife',
  minify: true,
  target: ['es2020', 'safari15'],
  legalComments: 'none',
  nodePaths: [join(here, 'node_modules')],
  write: false,
  logLevel: 'warning',
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');

let css = read('style.css')
  .replace('url(fonts/barlow-condensed-800-italic.woff2)', `url(data:font/woff2;base64,${b64('fonts/barlow-condensed-800-italic.woff2')})`)
  .replace('url(fonts/barlow-condensed-600.woff2)', `url(data:font/woff2;base64,${b64('fonts/barlow-condensed-600.woff2')})`)
  .replace(/<\/style/gi, '<\\/style');
if (css.includes('url(fonts/')) throw new Error('build: a font was not inlined');
const iconUri = 'data:image/svg+xml;base64,' + b64('icon.svg');

const notice = `<!--
  Loamline — freeride mountain biking in the browser.
  Single-file build generated by tools/build.mjs from src/. Do not edit this
  file by hand: edit src/ and run the build again.

  Includes three.js ${threeV} (https://threejs.org/), MIT License,
  Copyright © 2010-2024 three.js authors; and the Barlow Condensed typeface
  by Jeremy Tribby, SIL Open Font License 1.1. Full licence texts are in
  tools/THIRD_PARTY_LICENSES.txt.
-->`;

let out = html;
const swap = (from, to) => {
  if (!out.includes(from)) throw new Error('build: could not find in src/index.html: ' + from.slice(0, 80));
  out = out.replace(from, () => to);
};
out = out.replace(/\s*<script type="importmap">[\s\S]*?<\/script>/, '');
swap('<link rel="icon" href="icon.svg" type="image/svg+xml">', `<link rel="icon" href="${iconUri}" type="image/svg+xml">`);
swap('<link rel="stylesheet" href="style.css">', `<style>\n${css}</style>`);
swap('<script type="module" src="js/main.js"></script>', `<script>${js}</script>`);
out = out.replace('<!doctype html>\n', `<!doctype html>\n${notice}\n`);

const dest = join(root, 'index.html');
writeFileSync(dest, out);
console.log(`wrote ${dest} (${(statSync(dest).size / 1024).toFixed(0)} KB; three ${threeV})`);
